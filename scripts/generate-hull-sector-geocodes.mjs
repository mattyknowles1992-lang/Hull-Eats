/**
 * Fetches real UK coordinates from postcodes.io for Hull outward districts (HU1–HU16)
 * and sectors 1–9. Writes packages/types/src/hull-sector-geocodes.generated.ts
 *
 * Run: node scripts/generate-hull-sector-geocodes.mjs
 */

import { writeFileSync } from "node:fs";
import { dirname, join } from "node:path";
import { fileURLToPath } from "node:url";

const OUTWARDS = [
  "HU1", "HU2", "HU3", "HU4", "HU5", "HU6", "HU7", "HU8", "HU9",
  "HU10", "HU11", "HU12", "HU13", "HU14", "HU15", "HU16",
];
const SECTORS = ["1", "2", "3", "4", "5", "6", "7", "8", "9"];
const SUFFIX_PAIRS = [];
for (const l1 of "ABCDEFGHJKLMNPQRSTUVWXY") {
  for (const l2 of "ABCDEFGHJKLMNPQRSTUVWXY") {
    SUFFIX_PAIRS.push(`${l1}${l2}`);
  }
}

const sleep = (ms) => new Promise((resolve) => setTimeout(resolve, ms));

async function bulkPostcodes(postcodes) {
  const { ok, body } = await fetch("https://api.postcodes.io/postcodes", {
    method: "POST",
    headers: { "Content-Type": "application/json", Accept: "application/json" },
    body: JSON.stringify({ postcodes }),
  }).then(async (response) => ({ ok: response.ok, body: await response.json() }));

  if (!ok || !Array.isArray(body.result)) {
    return [];
  }

  return body.result;
}

async function geocodeOutcode(outcode) {
  const response = await fetch(`https://api.postcodes.io/outcodes/${encodeURIComponent(outcode)}`, {
    headers: { Accept: "application/json" },
  });
  if (!response.ok) {
    return null;
  }
  const body = await response.json();
  if (body.status !== 200 || !body.result) {
    return null;
  }
  return { lat: body.result.latitude, lng: body.result.longitude };
}

async function geocodeSector(outward, sector) {
  for (let offset = 0; offset < SUFFIX_PAIRS.length; offset += 90) {
    const slice = SUFFIX_PAIRS.slice(offset, offset + 90);
    const postcodes = slice.map((suffix) => `${outward} ${sector}${suffix}`);
    const results = await bulkPostcodes(postcodes);
    for (const entry of results) {
      if (entry.result?.latitude != null && entry.result?.longitude != null) {
        return {
          lat: entry.result.latitude,
          lng: entry.result.longitude,
          samplePostcode: entry.result.postcode,
        };
      }
    }
    await sleep(120);
  }
  return null;
}

async function main() {
  const outwards = {};
  const sectors = {};

  for (const outward of OUTWARDS) {
    console.log(`Outcode ${outward}…`);
    const out = await geocodeOutcode(outward);
    if (out) {
      outwards[outward] = out;
    }
    await sleep(100);

    sectors[outward] = {};
    for (const sector of SECTORS) {
      process.stdout.write(`  sector ${sector}… `);
      const hit = await geocodeSector(outward, sector);
      if (hit) {
        sectors[outward][sector] = hit;
        console.log(hit.samplePostcode);
      } else {
        console.log("miss");
      }
    }
  }

  const payload = {
    source: "postcodes.io",
    generatedAt: new Date().toISOString(),
    outwards,
    sectors,
  };

  const root = join(dirname(fileURLToPath(import.meta.url)), "..");
  const outPath = join(root, "packages/types/src/hull-sector-geocodes.generated.ts");
  const ts = `/** Generated by scripts/generate-hull-sector-geocodes.mjs — do not edit by hand. */\nexport const HULL_SECTOR_GEOCODES = ${JSON.stringify(payload, null, 2)} as const;\n`;
  writeFileSync(outPath, ts, "utf8");
  console.log(`Wrote ${outPath}`);
}

main().catch((error) => {
  console.error(error);
  process.exit(1);
});
